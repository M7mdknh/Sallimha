export function useT() {
  const lang = useLang();
  const table = lang === "ar" ? ar : en;
  return {
    lang,
    t: (key: StringKey) => table[key],
    state: (value: string) => STATES[lang][value] ?? value,
    alert: (kind: string) => ALERTS[lang][kind] ?? kind,
    error: (code: string) => (table as Record<string, string>)[`error_${code}`] ?? table.error_generic,
  };
}
